import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { MicroteiaRuntimeConfig } from './runtimeConfigShape.js';

/**
 * Diretório local da instalação: o pacote desempacotado e a configuração resolvida por `connect`.
 * Fica ao lado do `microteia.yaml` e é descartável — tudo aqui pode ser refeito a partir do tarball
 * mais um `connect`. A única coisa que NÃO é descartável é `functions/custom/`, e por isso o deploy
 * a preserva explicitamente.
 */
export const WORKSPACE_DIR = '.microteia';

export const RESOLVED_CONFIG_FILE = 'firebase-config.json';

export const workspacePath = (root: string): string => join(root, WORKSPACE_DIR);

export const resolvedConfigPath = (root: string): string =>
  join(workspacePath(root), RESOLVED_CONFIG_FILE);

export const kernelPath = (root: string, version: string): string =>
  join(workspacePath(root), 'kernel', version);

export const readResolvedConfig = async (root: string): Promise<MicroteiaRuntimeConfig> => {
  try {
    return JSON.parse(await readFile(resolvedConfigPath(root), 'utf8')) as MicroteiaRuntimeConfig;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      throw new Error(
        'This installation is not connected to a Firebase project yet. Run "microteia connect --project <id>".',
        { cause: error },
      );
    }
    throw error;
  }
};

export const writeResolvedConfig = async (
  root: string,
  config: MicroteiaRuntimeConfig,
): Promise<void> => {
  await writeFile(resolvedConfigPath(root), `${JSON.stringify(config, null, 2)}\n`);
};

/**
 * O arquivo que o navegador carrega ANTES do bundle. É o único ponto em que o projeto Firebase entra
 * numa instalação — ver `index.html` e `infrastructure/firebase/runtimeConfig.ts` no kernel.
 */
export const stampedConfigJs = (config: MicroteiaRuntimeConfig): string =>
  `// Generated by "microteia deploy". Do not edit by hand.\n`
  + `window.__MICROTEIA_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`;
