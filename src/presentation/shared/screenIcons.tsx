const SCREEN_ICON_OPTIONS: ScreenIconOption[] = SCREEN_ICON_KEYS.map((key) => ({
  key,
  label: screenIconLabel(key),
  Icon: SCREEN_ICONS[key],
}));

export const getScreenIconOptions = (): ScreenIconOption[] => SCREEN_ICON_OPTIONS;

export const getScreenIconType = (key: string): IconType =>
  SCREEN_ICONS[key as ScreenIconKey] ?? SCREEN_ICONS[FALLBACK_SCREEN_ICON];

export const getScreenIcon = (key: string, size = 20): React.ReactNode => {
  const Icon = getScreenIconType(key);
  return <Icon size={size} />;
};
