export type ScreenIconKey = (typeof SCREEN_ICON_KEYS)[number];

/**
 * O ícone desenhado quando a chave não é reconhecida. Ele existe para que uma tela nunca fique sem
 * marcador — nunca para tolerar um nome inventado, que é recusado no portão do pacote.
 */
export const FALLBACK_SCREEN_ICON: ScreenIconKey = 'apps';

const SCREEN_ICON_KEY_SET: ReadonlySet<string> = new Set(SCREEN_ICON_KEYS);

export const isScreenIconKey = (key: unknown): key is ScreenIconKey =>
  typeof key === 'string' && SCREEN_ICON_KEY_SET.has(key);

/** O rótulo traduzível de um ícone, no catálogo do `core.ui`. */
export const screenIconLabel = (key: ScreenIconKey): string => `@core.ui/icon.${key}`;
