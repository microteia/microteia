/**
 * Emite `sdk/types/microteia-host.d.ts` — os tipos dos módulos `@microteia/*`, `react` e
 * `styled-components` que o CÓDIGO de uma extensão (view, `startup`) pode importar.
 *
 *   npm run build:host-types            # regrava o arquivo
 *   npm run build:host-types -- --check # falha se estiver desatualizado (usado no verify)
 *
 * A fonte é `buildExtensionTypeDefs()`, o mesmo texto que o Monaco do editor de extensões já recebe
 * como `extraLib`. Um autor no VSCode e um autor na tela de autoria passam a ver EXATAMENTE a mesma
 * API — que era o único jeito de não ter duas descrições da mesma coisa envelhecendo em paralelo.
 *
 * O módulo é carregado com `sucrase`, não com o Vite: ele não importa nada em tempo de execução (só
 * template literals), e evitar subir um servidor aqui mantém o passo instantâneo.
 */
import { readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { transform } from 'sucrase';

const check = process.argv.includes('--check');
const root = process.cwd();
const source = join(root, 'src/presentation/shared/extensions/extensionTypeDefs.ts');
const output = join(root, 'sdk/types/microteia-host.d.ts');

const { code } = transform(readFileSync(source, 'utf8'), {
  transforms: ['typescript', 'imports'],
  production: true,
});

const moduleObject = { exports: {} };
new Function('require', 'module', 'exports', code)(
  (name) => { throw new Error(`extensionTypeDefs must not import anything (tried "${name}").`); },
  moduleObject,
  moduleObject.exports,
);

const { buildExtensionTypeDefs } = moduleObject.exports;
if (typeof buildExtensionTypeDefs !== 'function') {
  throw new Error('extensionTypeDefs no longer exports buildExtensionTypeDefs.');
}

const header = `// Generated by "npm run build:host-types". Do not edit by hand.
//
// The modules a Microteia extension may import from its view or startup code. Anything not declared
// here is not reachable: the runtime resolves imports against a fixed allowlist and throws otherwise.

`;

const content = `${header}${buildExtensionTypeDefs().trim()}\n`;
const declared = [...content.matchAll(/declare module '([^']+)'/g)].map((match) => match[1]);

/**
 * O `?raw` não é um módulo do host: é o MECANISMO de autoria — a forma de a fonte de uma view morar num
 * arquivo checado e ainda assim viajar como dado no `.json`. Sem esta declaração o `tsc` acusa
 * "cannot find module './views/X.tsx?raw'" no import mais importante de um `plugin.ts`, e foi o que
 * aconteceu. Fica em arquivo separado de propósito: `microteia-host.d.ts` é a API curada, e é ela que o
 * MCP serve por módulo.
 */
const RAW_TYPES = `// Generated by "npm run build:host-types". Do not edit by hand.
//
// Importing a file with "?raw" gives you its TEXT, not its exports. It is how the source of a view lives
// in a real, type-checked .tsx file and still travels as data inside the extension's .json:
//
//     import VIEW_SOURCE from './views/Summary.view.tsx?raw';
//
// The compiler replaces the import with the file's contents at build time.

declare module '*?raw' {
  const content: string;
  export default content;
}
`;

const rawOutput = join(root, 'sdk/types/microteia-raw.d.ts');

if (check) {
  const currentRaw = existsSync(rawOutput) ? readFileSync(rawOutput, 'utf8') : null;
  if (currentRaw !== RAW_TYPES) {
    console.error('❌ sdk/types/microteia-raw.d.ts está desatualizado — rode "npm run build:host-types".');
    process.exitCode = 1;
  }
  const current = existsSync(output) ? readFileSync(output, 'utf8') : null;
  if (current === content) {
    console.log(`✔️  sdk/types/microteia-host.d.ts (em dia, ${declared.length} módulos)`);
  } else {
    console.error('❌ sdk/types/microteia-host.d.ts está desatualizado — rode "npm run build:host-types".');
    process.exitCode = 1;
  }
} else {
  mkdirSync(join(root, 'sdk/types'), { recursive: true });
  writeFileSync(output, content);
  writeFileSync(rawOutput, RAW_TYPES);
  console.log(`✏️  gerado: sdk/types/microteia-host.d.ts (${declared.length} módulos: ${declared.join(', ')})`);
}
